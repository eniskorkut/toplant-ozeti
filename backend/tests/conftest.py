def _generate_audio(path: Path, codec_args: list[str], container_args: list[str]) -> None:
    command = [
        "ffmpeg",
        "-nostdin",
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-f",
        "lavfi",
        "-i",
        "sine=frequency=440:duration=2",
        *codec_args,
        *container_args,
        str(path),
    ]
    subprocess.run(command, check=True, capture_output=True, text=True)


@pytest.fixture(scope="session")
def audio_samples(tmp_path_factory: pytest.TempPathFactory) -> dict[str, Path]:
    """Deterministic 2 second audio generated by the container's own ffmpeg."""
    directory = tmp_path_factory.mktemp("audio-samples")

    webm_opus = directory / "sample.webm"
    _generate_audio(
        webm_opus,
        ["-c:a", "libopus", "-b:a", "64k", "-ac", "1"],
        ["-f", "webm"],
    )

    mp4_aac = directory / "sample.mp4"
    _generate_audio(
        mp4_aac,
        ["-c:a", "aac", "-b:a", "64k", "-ac", "1"],
        ["-f", "mp4"],
    )

    return {"webm": webm_opus, "mp4": mp4_aac}


