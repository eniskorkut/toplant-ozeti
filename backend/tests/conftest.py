def upload(
    client: TestClient,
    content: bytes,
    *,
    mime_type: str = "audio/webm;codecs=opus",
    filename: str = "recording.webm",
    content_type: str | None = None,
):
    return client.post(
        "/api/recordings",
        files={"audio": (filename, content, content_type or mime_type)},
        data={"mime_type": mime_type, "client_duration_seconds": "2.0"},
    )
